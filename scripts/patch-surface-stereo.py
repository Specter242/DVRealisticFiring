#!/usr/bin/env python3
"""Make a surface shader's generated code the mod's stereo-ready shader.

Unity strips its own single-pass stereo variants from a bundle built
without VR, and a surface shader's own code comes after the includes that
switch stereo on. So the mod ships the code Unity generates for each
surface shader (fx Assets/Editor/SurfaceExport.cs writes it out), with a
variant on the mod's keyword RF_SINGLE_PASS_STEREO that defines Unity's
UNITY_SINGLE_PASS_STEREO before those includes, in the passes drawn for
the eyes (forward base, forward add where there is one, deferred). The shadow caster and meta
passes stay as they are: shadow maps are drawn from the lights, not the
eyes. Each program becomes HLSL, not CG: Unity includes the stereo
switches at the top of a CG program, before the define. The mod turns the
keyword on for stereo cameras.

Usage: patch-surface-stereo.py GENERATED.shader SHADER_NAME SOURCE_NAME OUTPUT.shader
"""

import re
import sys

STEREO = """// Realistic Firing: single-pass stereo on the mod's own keyword.
#pragma multi_compile __ RF_SINGLE_PASS_STEREO
#if defined(RF_SINGLE_PASS_STEREO)
#define UNITY_SINGLE_PASS_STEREO 1
#endif
"""

EYE_PASSES = ('"ForwardBase"', '"ForwardAdd"', '"Deferred"')


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__.strip().splitlines()[-1])
    generated, name, source, output = sys.argv[1:]
    text = open(generated, encoding="utf-8").read()

    header = re.search(r'^Shader "[^"]+"', text, re.M)
    if not header:
        sys.exit("no Shader line")
    text = text[:header.start()] + \
        f"// Generated by Unity from {source} (Surface/), with a single-pass stereo\n" \
        f"// variant added by scripts/patch-surface-stereo.py: change the surface\n" \
        f"// shader there, export it (SurfaceExport), and patch it again.\n" + \
        f'Shader "{name}"' + text[header.end():]
    # Unity's own line markers, meaningless outside its generator.
    text = re.sub(r"^#LINE \d+\n", "", text, flags=re.M)
    # Every pass includes HLSLSupport and UnityShaderVariables itself.
    text = re.sub(r"^CGPROGRAM$", "HLSLPROGRAM", text, flags=re.M)
    text = re.sub(r"^ENDCG$", "ENDHLSL", text, flags=re.M)

    passes = text.split("\tPass {")
    found = set()
    for i in range(1, len(passes)):
        tags = passes[i][:400]
        mode = next((mode for mode in EYE_PASSES if f'"LightMode" = {mode}' in tags), None)
        if mode is None:
            continue
        marker = '#include "HLSLSupport.cginc"\n'
        if passes[i].count(marker) != 1:
            sys.exit(f"pass {i}: expected one HLSLSupport include")
        passes[i] = passes[i].replace(marker, STEREO + marker, 1)
        found.add(mode)
    patched = len(found)
    # Every eye pass the shader has; a shader lit only by its own light
    # (noforwardadd: the fire-lit firebox) has no forward add.
    if '"ForwardBase"' not in found or '"Deferred"' not in found:
        sys.exit(f"patched {sorted(found)}: expected the forward base and deferred passes")
    open(output, "w", encoding="utf-8").write("\tPass {".join(passes))
    print(f"wrote {output}: {name}, stereo in {patched} passes")


if __name__ == "__main__":
    main()
